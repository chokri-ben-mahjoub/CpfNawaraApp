/// Remplace les marqueurs `{nom}` d'une chaîne traduite par leurs valeurs.
String fill(String template, Map<String, String> values) {
  var result = template;
  values.forEach((key, value) => result = result.replaceAll('{$key}', value));
  return result;
}

